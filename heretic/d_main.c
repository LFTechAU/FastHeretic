static void FH_DrawFPS(void)
{
	char text[8];
	int tics;

	fps_frames++;
	tics = ticcount - fps_lasttic;
	if (tics >= 35)
	{
		fps_value = fps_frames * 35 / tics;
		fps_frames = 0;
		fps_lasttic = ticcount;
	}
	if (fh_debugcard)
	{ // show the frame rate in BCD on the POST code display
		int v = fps_value, out;
		if (fh_debugcard == 2)
		{
			if (v > 99) v = 99;
			out = ((v / 10) << 4) | (v % 10);
			outp(fh_debugport, out);
		}
		else
		{
			if (v > 9999) v = 9999;
			out = ((v / 1000) << 12) | (((v / 100) % 10) << 8)
				| (((v / 10) % 10) << 4) | (v % 10);
			outpw(fh_debugport, out);
		}
	}
	if (fh_showfps)
	{
		sprintf(text, "%d", fps_value);
		MN_DrTextA(text, FH_VIRTX(viewwindowx + scaledviewwidth) - MN_TextAWidth(text) - 4,
			FH_VIRTY(viewwindowy) + 2);
	}
}

void D_Display(void)
{
	extern boolean MenuActive;
	extern boolean askforquit;
#ifdef FH_DIRECT
	extern int InfoType;
	extern int screenblocks;
#endif

	// Change the view size if needed
	if(setsizeneeded)
	{
		R_ExecuteSetViewSize();
	}

//
// do buffered drawing
//
	switch (gamestate)
	{
	case GS_LEVEL:
		if (!gametic)
			break;
		if (automapactive)
			AM_Drawer ();
		else
		{
			FH_InterpolateBegin();
			R_RenderPlayerView (&players[displayplayer]);
			FH_InterpolateEnd();
			if (fh_usedmmx)
				FH_EMMS();      // MMX drawers ran: free the FPU again
		}
#ifdef FH_DIRECT
		if (!automapactive && !(MenuActive && InfoType) && FHY_Direct())
		{ // view is in the page already: status bar, border, then overlays
			fh_directframe = 1;
			if (screenblocks > 10)
				FHY_OverlayOn();
			fhy_sbmode = 1;
			SB_Drawer();
			fhy_sbmode = 0;
			FHY_OverlayOff();
			FHY_Composite();
			FHY_OverlayOn();
			FH_DrawFPS();
			CT_Drawer();
			break;
		}
#endif
		FH_DrawFPS();
		CT_Drawer();
		UpdateState |= I_FULLVIEW;
		SB_Drawer();
		break;
	case GS_INTERMISSION:
		IN_Drawer ();
		break;
	case GS_FINALE:
		F_Drawer ();
		break;
	case GS_DEMOSCREEN:
		D_PageDrawer ();
		break;
	}

	if(paused && !MenuActive && !askforquit)
	{
		if(!netgame)
		{
			V_DrawPatch(160, FH_VIRTY(viewwindowy)+5, W_CacheLumpName("PAUSED",
				PU_CACHE));
		}
		else
		{
			V_DrawPatch(160, 70, W_CacheLumpName("PAUSED",
				PU_CACHE));
		}
	}
	// Handle player messages
	DrawMessage();

	if (fh_quittic >= 0 && gamestate == GS_LEVEL)
	{
		if (!fh_quitframes++)
			fh_quitstart = ticcount;
		if (gametic >= fh_quittic)
		{
			FILE *f = fopen("FHQUIT.TXT", "w");
			int t = ticcount - fh_quitstart;
			fprintf(f, "%d frames in %d tics: %d.%02d fps\n", fh_quitframes, t,
				fh_quitframes * 35 / t, (fh_quitframes * 3500 / t) % 100);
			fclose(f);
			I_Quit();
		}
	}
	if (fh_shottic >= 0 && gametic == fh_shottic && gamestate == GS_LEVEL)
	{
		if (fh_shotmenu)
			MN_FHShowMenu(fh_shotmenu);
		MN_Drawer();
#ifdef FH_DIRECT
		if (fh_directframe)
			FHY_ReadPage();
#endif
		M_ScreenShot ();
		players[consoleplayer].message = NULL;
		fh_shottic = -1;
	}

	// Menu drawing
	MN_Drawer();
#ifdef FH_DIRECT
	FHY_OverlayOff();
#endif

	// Send out any new accumulation
	NetUpdate();

	// Flush buffered stuff to screen
	I_Update();
}

//---------------------------------------------------------------------------
//
// PROC D_DoomLoop
//
//---------------------------------------------------------------------------

void D_DoomLoop(void)
{
	if(M_CheckParm("-debugfile"))
	{
		char filename[20];
		sprintf(filename, "debug%i.txt", consoleplayer);
		debugfile = fopen(filename,"w");
	}
	I_InitGraphics();
	while(1)
	{
		if (fh_benchnext)
			FH_BenchNext();     // FastHeretic -bench: next run
		// Frame syncronous IO operations
		I_StartFrame();

		// Process one or more tics
		if(singletics)
		{
			I_StartTic();
			D_ProcessEvents();
			G_BuildTiccmd(&netcmds[consoleplayer][maketic%BACKUPTICS]);
			if (advancedemo)
				D_DoAdvanceDemo ();
			G_Ticker();
			gametic++;
			maketic++;
		}
		else if (fh_uncapped && gamestate == GS_LEVEL && !netgame)
		{ // FastHeretic: draw frames between tics
			FH_SetUncapped(1);
			FH_TryRunTicsUncapped();
		}
		else
		{
			FH_SetUncapped(0);
			// Will run at least one tic
			TryRunTics();
		}

		// Move positional sounds
		S_UpdateSounds(players[consoleplayer].mo);
		D_Display();
		FH_BenchFrame();
	}
}

